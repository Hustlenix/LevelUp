"use client";

import { useMemo, useState } from "react";
import Link from "next/link";
import { AlertCircle, BookOpen, MessageCircle, Sparkles } from "lucide-react";
import type { SearchDoc } from "@/lib/types";
import { aiSourceLabel, AI_LIMITS } from "@/lib/ai/contracts";
import type { AiContext, AiSource, CoachResult } from "@/lib/ai/contracts";
import { retrieveLevelUpContent } from "@/lib/ai/retrieval";
import { createAiServices } from "@/lib/ai/services";
import { validateCoachRequest } from "@/lib/ai/schemas";
import { buildLifeosAiContext } from "@/lib/ai/lifeos-context";
import { useOSStore } from "@/lib/os";
import { useClientToday } from "@/lib/clientToday";
import { useStudentProfile } from "@/lib/studentProfile";
import { useGamification } from "@/lib/useGamification";
import { WorkspaceHeader } from "@/components/workspace";

const buttonClass =
  "inline-flex min-h-11 items-center justify-center gap-2 rounded-lg bg-gold px-4 py-2 text-sm font-semibold text-paper transition-colors hover:bg-gold-deep focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-gold disabled:cursor-not-allowed disabled:opacity-50";

function ResultSource({
  source,
  note,
  fallbackReason,
}: {
  source: AiSource;
  note?: string;
  fallbackReason?: string;
}) {
  const fallbackNote =
    fallbackReason === "ollama-unavailable"
      ? "Ollama was unavailable, so this answer was generated by the deterministic fallback."
      : fallbackReason === "no-ollama"
        ? "Ollama is not available, so this answer was generated by the deterministic fallback."
        : "This answer was generated locally from your saved LevelUp state.";
  return (
    <div
      className="mt-3 rounded-lg border border-line/80 bg-paper-deep/60 px-3 py-2 text-xs text-ink-soft"
      role="status"
      aria-live="polite"
    >
      <span className="font-semibold text-ink">{aiSourceLabel(source)}.</span>{" "}
      {note ?? fallbackNote}
    </div>
  );
}

function ErrorMessage({ message }: { message: string }) {
  return (
    <div
      className="mt-3 flex items-start gap-2 rounded-lg border border-rose/30 bg-rose/5 px-3 py-2 text-sm text-ink"
      role="alert"
    >
      <AlertCircle className="mt-0.5 h-4 w-4 shrink-0 text-rose" aria-hidden="true" />
      <span>{message}</span>
    </div>
  );
}

interface CoachViewProps {
  documents: SearchDoc[];
}

/** Dedicated AI advisor page: ask what to focus on next, grounded in saved OS state. */
export default function CoachView({ documents }: CoachViewProps) {
  const os = useOSStore();
  const date = useClientToday();
  const profile = useStudentProfile();
  const gamification = useGamification();

  // buildLifeosAiContext derives progression internally, which requires a real
  // date (computeProgression(parseDay("")) throws). useClientToday returns ""
  // during static prerender, so defer the whole context until the client date
  // snaps in after hydration — the same guard LevelUpOSWorkspace uses.
  const context = useMemo<AiContext | null>(() => {
    if (!date) return null;
    return buildLifeosAiContext({ date, os, profile, gamification: gamification.state });
  }, [date, os, profile, gamification.state]);

  const services = useMemo(() => createAiServices(), []);
  const [question, setQuestion] = useState("");
  const [coach, setCoach] = useState<CoachResult | null>(null);
  const [coachMeta, setCoachMeta] = useState<{
    source: AiSource;
    note?: string;
    fallbackReason?: string;
  } | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  async function askCoach(event?: React.FormEvent) {
    event?.preventDefault();
    if (!context) return;
    const request = validateCoachRequest({ question });
    if (!request) {
      setError("Ask a short question so the Coach can give you a specific next move.");
      return;
    }
    setBusy(true);
    setError(null);
    const refs = retrieveLevelUpContent(documents, request.question, AI_LIMITS.maxReferences);
    const result = await services.coach(request, context, refs);
    setBusy(false);
    if (!result.ok) {
      setError(result.error.message);
      return;
    }
    setCoach(result.value);
    setCoachMeta({ source: result.source, note: result.note, fallbackReason: result.fallbackReason });
  }

  return (
    <div className="mx-auto w-full max-w-6xl px-5 py-8 sm:px-8 sm:py-12">
      <WorkspaceHeader
        eyebrow="Coach"
        title="Turn today into a next move"
        description="Ask what to focus on, and the Coach grounds its answer in your saved plan, goals, and progress."
      />

      <section
        className="mt-8 rounded-2xl border border-line bg-card p-6 shadow-xs sm:p-8"
        aria-labelledby="coach-heading"
      >
        <div className="flex flex-wrap items-start justify-between gap-4">
          <div className="max-w-2xl">
            <div className="flex items-center gap-2 text-xs font-semibold uppercase tracking-[0.2em] text-gold">
              <Sparkles className="h-4 w-4" aria-hidden="true" />
              LevelUp Coach
            </div>
            <h2 id="coach-heading" className="mt-2 font-display text-2xl font-bold tracking-tight text-ink">
              Ask for your next move
            </h2>
            <p className="mt-2 text-sm leading-relaxed text-ink-soft">
              Answers are generated locally from the state saved on this device — plans, goals,
              streaks, and progress. Nothing is sent to a remote AI service.
            </p>
          </div>
          <span className="rounded-full border border-line bg-paper-deep px-3 py-1 text-[0.6875rem] font-semibold uppercase tracking-wider text-ink-faint">
            Local-only AI
          </span>
        </div>

        <div className="mt-6 rounded-xl border border-line bg-paper p-5">
          <div className="flex items-start justify-between gap-3">
            <div>
              <p className="font-display text-xs font-semibold uppercase tracking-[0.18em] text-gold">
                Ask Coach
              </p>
              <h3 className="mt-1 font-display text-lg font-semibold text-ink">
                What should happen next?
              </h3>
            </div>
            <MessageCircle className="h-5 w-5 text-ink-faint" aria-hidden="true" />
          </div>

          <div className="mt-3 flex flex-wrap gap-2">
            {["What should I focus on today?", "What should I learn next?", "Why am I falling behind?"].map(
              (prompt) => (
                <button
                  key={prompt}
                  type="button"
                  onClick={() => setQuestion(prompt)}
                  className="min-h-9 rounded-full border border-line bg-card px-3 py-1.5 text-xs text-ink-soft transition-colors hover:border-gold hover:text-gold focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-gold"
                >
                  {prompt}
                </button>
              ),
            )}
          </div>

          <form className="mt-3" onSubmit={askCoach}>
            <label htmlFor="coach-question" className="sr-only">
              Ask the LevelUp Coach
            </label>
            <textarea
              id="coach-question"
              maxLength={AI_LIMITS.questionChars}
              rows={3}
              value={question}
              onChange={(event) => setQuestion(event.target.value)}
              placeholder="Ask about today, recovery, progress, or what to learn next."
              className="w-full resize-y rounded-lg border border-line bg-card px-3 py-2 text-sm text-ink placeholder:text-ink-faint focus:border-gold focus:outline-none focus-visible:ring-2 focus-visible:ring-gold/40"
            />
            <button type="submit" disabled={busy || !context} className={`mt-3 ${buttonClass}`}>
              <MessageCircle className="h-4 w-4" aria-hidden="true" />
              {busy ? "Thinking…" : "Ask Coach"}
            </button>
          </form>

          {coach ? (
            <div className="mt-4 border-t border-line pt-4">
              <p className="text-sm leading-relaxed text-ink">{coach.answer}</p>
              <ul className="mt-3 space-y-1.5 text-xs text-ink-soft">
                {coach.nextActions.map((action) => (
                  <li key={action} className="flex gap-2">
                    <span className="text-gold">→</span>
                    <span>{action}</span>
                  </li>
                ))}
              </ul>
              <p className="mt-3 text-[0.6875rem] text-ink-faint">Basis: {coach.basis.join(" · ")}</p>
              {coach.suggestedChapterSlug ? (
                <Link
                  href={`/chapters/${coach.suggestedChapterSlug}/`}
                  className="mt-3 inline-flex min-h-9 items-center gap-1 text-xs font-semibold text-gold hover:underline focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-gold"
                >
                  <BookOpen className="h-3 w-3" aria-hidden="true" />
                  Read the suggested chapter
                </Link>
              ) : null}
              {coachMeta ? (
                <ResultSource
                  source={coachMeta.source}
                  note={coachMeta.note}
                  fallbackReason={coachMeta.fallbackReason}
                />
              ) : null}
            </div>
          ) : (
            <p className="mt-4 text-xs leading-relaxed text-ink-faint">
              No answer yet. Ask a question to get a next move grounded in your own progress.
            </p>
          )}

          {error ? <ErrorMessage message={error} /> : null}
        </div>
      </section>
    </div>
  );
}
