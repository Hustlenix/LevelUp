import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdir } from "node:fs/promises";
const base = process.argv[2] || "http://localhost:3113";
const browser = await chromium.launch();
const errors = [];
let checks = 0;
try {
  const context = await browser.newContext({ reducedMotion: "reduce", viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  page.on("pageerror", e => errors.push(e.message));
  page.on("dialog", dialog => dialog.accept());
  await page.goto(`${base}/chapters/hyperfocus/`);
  await page.locator("#chapter-guide").getByRole("button", { name: "Save as a next action" }).click();
  assert.ok(await page.locator("#chapter-guide").getByRole("button", { name: "Saved to next actions" }).isDisabled());
  await page.goto(`${base}/today/`);
  await page.getByRole("region", { name: "Next actions" }).waitFor();
  assert.ok(await page.getByRole("region", { name: "Next actions" }).isVisible()); checks += 2;
  await page.goto(`${base}/small-steps/`);
  await page.getByLabel("What are you trying to start?").fill("My existing draft");
  await page.getByLabel("One action I can do now").fill("Open my notes");
  await page.getByLabel("When I return…").fill("Remember page three");
  await page.getByRole("button", { name: "Open action", exact: true }).click();
  assert.equal(await page.evaluate(() => document.activeElement?.id), "small-step-editor"); checks++;
  assert.notEqual(await page.getByLabel("What are you trying to start?").inputValue(), "My existing draft");
  assert.ok(await page.getByRole("region", { name: "Next actions" }).getByText("My existing draft", { exact: true }).isVisible());
  await page.getByRole("button", { name: "Open action", exact: true }).click();
  assert.equal(await page.getByLabel("When I return…").inputValue(), "Remember page three");
  await page.getByRole("button", { name: /^Remove / }).click();
  await page.getByRole("button", { name: "Undo", exact: true }).click();
  await page.reload();
  assert.equal(await page.getByRole("region", { name: "Next actions" }).getByRole("listitem").count(), 1); checks += 4;
  await page.goto(`${base}/protocols/`);
  await page.getByRole("button", { name: "Show all 13 plans" }).click();
  assert.equal(await page.locator("#ready-plans article").count(), 13);
  await page.getByRole("button", { name: "Show fewer plans" }).click();
  assert.equal(await page.locator("#ready-plans article").count(), 6); checks += 2;
  await page.getByLabel("Find a practice").fill("zzzzzz");
  assert.ok(await page.getByText("No plans match those filters. Try a broader search.").isVisible());
  await page.getByRole("button", { name: "Clear filters" }).click();
  await page.getByRole("button", { name: "Get started", exact: true }).click();
  await page.getByLabel("Time to set up").selectOption("2");
  assert.equal(await page.locator("#ready-plans article").count(), 1);
  await page.locator("#ready-plans article").getByRole("button").click();
  const runner = page.getByLabel("Selected practice", { exact: true });
  await runner.locator("textarea").fill("My two minute plan");
  await runner.getByRole("checkbox").first().check();
  await page.locator("#practice-plan-picker").selectOption("morning-plan");
  await runner.locator("textarea").fill("My morning draft");
  await page.locator("#practice-plan-picker").selectOption("tiny-start");
  assert.equal(await runner.locator("textarea").inputValue(), "My two minute plan");
  assert.ok(await runner.getByRole("checkbox").first().isChecked());
  await page.reload();
  await page.locator("#practice-plan-picker").selectOption("tiny-start");
  assert.equal(await runner.locator("textarea").inputValue(), "My two minute plan"); checks += 5;
  const peer = await context.newPage(); peer.on("dialog", d => d.accept());
  await peer.goto(`${base}/protocols/`);
  await peer.locator("#practice-plan-picker").selectOption("tiny-start");
  await peer.getByLabel("Selected practice", { exact: true }).locator("textarea").fill("Updated in another tab");
  await page.waitForFunction(() => document.querySelector('[aria-label="Selected practice"] textarea').value === "Updated in another tab");
  await peer.close(); checks++;
  await runner.getByRole("button", { name: "Save practice record", exact: true }).click();
  assert.equal(await runner.locator("textarea").inputValue(), "Updated in another tab");
  assert.ok(await runner.locator("textarea").isDisabled());
  await page.reload();
  await page.locator("#practice-plan-picker").selectOption("tiny-start");
  assert.equal(await runner.locator("textarea").inputValue(), "");
  await runner.locator("summary").filter({ hasText: "Last record" }).click();
  assert.ok(await runner.getByText("Updated in another tab", { exact: true }).isVisible()); checks += 4;
  for (const theme of ["light", "dark", "deepwork", "cyberpunk"]) {
    await page.evaluate(theme => document.documentElement.dataset.theme = theme, theme);
    for (const width of [320, 375, 768, 1440]) {
      await page.setViewportSize({ width, height: 900 });
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${theme}/${width} overflow`); checks++;
    }
  }
  await page.evaluate(() => { document.documentElement.dataset.theme = "light"; window.scrollTo(0, 0); });
  await mkdir(".next/connected-practice-qa", { recursive: true });
  await page.screenshot({ path: ".next/connected-practice-qa/library-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 375, height: 900 });
  await page.screenshot({ path: ".next/connected-practice-qa/library-mobile.png", fullPage: true });
  for (const [route, name] of [["backup", "Export full backup"], ["progress", "Export backup"]]) {
    await page.goto(`${base}/${route}/`);
    if (route === "progress") await page.locator("summary").filter({ hasText: "Reading, focus, and workspace record" }).click();
    const downloading = page.waitForEvent("download");
    await page.getByRole("button", { name, exact: true }).click();
    const stream = await (await downloading).createReadStream();
    const chunks = []; for await (const chunk of stream) chunks.push(chunk);
    const data = JSON.parse(Buffer.concat(chunks).toString());
    assert.equal(data.practiceDrafts.entries["morning-plan:library"].notes, "My morning draft");
    assert.equal(data.smallSteps.queue.length, 1);
    const before = await page.evaluate(() => localStorage.getItem("levelup-practice-drafts-v1"));
    await page.locator('input[type="file"]').setInputFiles({ name: "bad.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify({ ...data, practiceDrafts: { entries: [] } })) });
    await page.getByText("practiceDrafts has an invalid shape.", { exact: true }).waitFor();
    assert.equal(await page.evaluate(() => localStorage.getItem("levelup-practice-drafts-v1")), before);
    data.practiceDrafts.entries["morning-plan:library"].notes = "Restored draft";
    await page.locator('input[type="file"]').setInputFiles({ name: "backup.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(data)) });
    await page.waitForFunction(() => JSON.parse(localStorage.getItem("levelup-practice-drafts-v1")).entries["morning-plan:library"].notes === "Restored draft");
    // Reset this draft for the next export surface, through the actual UI.
    await page.goto(`${base}/protocols/`); await page.locator("#practice-plan-picker").selectOption("morning-plan"); await runner.locator("textarea").fill("My morning draft");
    checks += 4;
  }
  await page.evaluate(() => { const original = Storage.prototype.setItem; Storage.prototype.setItem = function(k, v) { if (k === "levelup-practice-drafts-v1") throw new DOMException("quota", "QuotaExceededError"); return original.call(this, k, v); }; });
  await runner.locator("textarea").fill("Recover this unsaved draft");
  assert.ok(await runner.getByRole("alert").isVisible());
  assert.equal(await runner.locator("textarea").inputValue(), "Recover this unsaved draft"); checks += 2;
  await page.goto(`${base}/protocols/#protocol-2-1`);
  await page.waitForFunction(() => document.getElementById("protocol-2-1")?.open);
  assert.equal(await page.locator("#original-protocols details[open]").count(), 1);
  assert.equal(await page.locator("#original-protocols details").count(), 13); checks += 2;
  assert.equal(await page.locator("#original-protocols details").nth(1).getAttribute("id"), "protocol-2-2"); checks++;
  assert.deepEqual(errors, []);
  console.log(`PASS: ${checks} connected-practice browser checks; no page errors.`);
  await context.close();
} finally { await browser.close(); }
